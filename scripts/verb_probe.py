"""V0 verb check (plans/steps/VERB_LEXICON.md): a linear probe on GysBERT in-context token embeddings.

Read-only on corpus data, no LLM. Is this token a verb *in this occurrence*?

- Texts: the 39 frozen T1b works plus the 6 cookbooks in the zip, typed recipe / medical / other.
- Positives: occurrences of forms of known verbs (the manual lexicon's infinitives, the IRREGULAR table, a
  few light verbs), generated by `verb_forms.forms_for`. Only forms that occur in the texts are used, and
  known noun homographs (rook, smaak, zout…) are left out of training.
- Negatives: food-vocabulary nouns plus a hand list of function words, adjectives, adverbs and common
  nouns, so the probe learns "verb", not "not a food noun".
- Evaluation: grouped by lemma (unseen verbs), reported per source type. Gate (VERB_LEXICON.md V0):
  ≥ 0.9 overall and ≥ 0.85 per source type, otherwise the probe only ranks the review.
- Then every candidate form in `candidates_raw.csv` is scored on its occurrences in the same texts.

    uv run python scripts/verb_probe.py
    # -> docs/evidence/verb_lexicon/{probe_seeds.csv,probe_report.md,candidates_scored.csv}
"""

