def _source_type(fn: str, title: str) -> str:
    r = infer_text_regime(corpus=CORPUS, title=title, source_path=fn)
    return "recipe" if r is TextRegime.RECIPE_PRACTICE else "medical" if r is TextRegime.MEDICAL else "other"


def load_texts() -> dict[str, tuple[str, str]]:
    works = pd.read_csv(ROOT / "docs" / "evidence" / "triangulation_b" / "works.csv")
    titles = dict(zip(works.filename, works.title.astype(str)))
    out = {}
    with zipfile.ZipFile(resolve("dbnl_xml")) as z:
        for fn in sorted(set(works.filename) | set(COOKBOOKS)):
            text = render_tei(z.read(fn).decode("utf-8", "replace"), work_id=fn).text
            out[fn] = (text, _source_type(fn, titles.get(fn, fn)))
    return out


def seeds(vocab: set[str]) -> pd.DataFrame:
    """form, lemma, label (1 verb / 0 not), source. Restricted to forms that occur in the texts."""
    terms = load_food_terms()
    food = {t for t in set(alt_label_index(terms)) | {str(p).strip().lower() for p in terms["Pref_label"].dropna()}
            if " " not in t and len(t) >= 3}
    lemmas: dict[str, str] = {}
    for form, entry in _DEFAULT_LEXICON.entries.items():
        if not all(s.startswith("corpus:") for s in entry.sources) and form.endswith("en") and " " not in form:
            lemmas[form] = "lexicon_manual"
    for lem in IRREGULAR:
        lemmas.setdefault(lem, "irregular_table")
    for lem in LIGHT_VERBS:
        lemmas.setdefault(lem, "light_verb")
    pos = {}
    for lem, src in lemmas.items():
        for form in forms_for(lem):
            if form in vocab and len(form) >= 3 and form not in food and form not in HOMOGRAPHS \
                    and form not in NEGATIVE_WORDS:
                pos.setdefault(form, (lem, src))
    neg = {}
    for w in food:
        if w in vocab and w not in pos and w not in HOMOGRAPHS:
            neg[w] = (w, "food_vocabulary")
    for w in NEGATIVE_WORDS:
        if w in vocab and w not in pos:
            neg[w] = (w, "hand_negative_list")
    rows = [{"form": f, "lemma": l, "label": 1, "source": s} for f, (l, s) in pos.items()]
    rows += [{"form": f, "lemma": l, "label": 0, "source": s} for f, (l, s) in neg.items()]
    return pd.DataFrame(rows)


def occurrences(texts, forms: set[str], rng: random.Random) -> list[dict]:
    """Sample up to PER_WORK per work and PER_FORM in total for each form."""
    hits = defaultdict(list)
    for fn, (text, stype) in texts.items():
        by_form = defaultdict(list)
        for m in re.finditer(r"[A-Za-zÀ-ÿ]+", text):
            w = m.group(0).lower()
            if w in forms:
                by_form[w].append(m.start())
        for w, offs in by_form.items():
            for o in rng.sample(offs, min(PER_WORK, len(offs))):
                hits[w].append({"form": w, "work": fn, "stype": stype, "start": o, "end": o + len(w),
                                "context": text[max(0, o - RADIUS):o + len(w) + RADIUS],
                                "t0": min(o, RADIUS)})
    out = []
    for w, hs in hits.items():
        out += rng.sample(hs, min(PER_FORM, len(hs)))
    return out


def embed(occ: list[dict], batch: int = 32) -> np.ndarray:
    import torch
    from transformers import AutoModel, AutoTokenizer

    dev = "mps" if torch.backends.mps.is_available() else "cpu"
    tok = AutoTokenizer.from_pretrained(MODEL, local_files_only=True)
    model = AutoModel.from_pretrained(MODEL, local_files_only=True, output_hidden_states=True).to(dev).eval()
    vecs = []
    t0 = time.monotonic()
    for i in range(0, len(occ), batch):
        chunk = occ[i:i + batch]
        enc = tok([o["context"] for o in chunk], return_offsets_mapping=True, truncation=True, max_length=192,
                  padding=True, return_tensors="pt")
        offsets = enc.pop("offset_mapping")
        with torch.no_grad():
            hs = model(**{k: v.to(dev) for k, v in enc.items()}).hidden_states
        layer = torch.stack(hs[-4:]).mean(0).cpu()            # mean of the last four layers
        for j, o in enumerate(chunk):
            a, b = o["t0"], o["t0"] + (o["end"] - o["start"])
            idx = [k for k, (s, e) in enumerate(offsets[j].tolist()) if e > s and s < b and e > a]
            vecs.append(layer[j, idx].mean(0).numpy() if idx else np.zeros(layer.shape[-1], dtype=np.float32))
        if (i // batch) % 50 == 0:
            print(f"  embedded {i + len(chunk)}/{len(occ)} ({(time.monotonic() - t0) / 60:.1f} min)", flush=True)
    return np.stack(vecs)


def main() -> None:
    from sklearn.linear_model import LogisticRegression
    from sklearn.model_selection import GroupKFold

    from scripts.eval_gold_by_position import wilson

    rng = random.Random(SEED)
    print("rendering texts…", flush=True)
    texts = load_texts()
    vocab = set()
    for text, _ in texts.values():
        vocab |= {w.lower() for w in re.findall(r"[A-Za-zÀ-ÿ]+", text)}
    sd = seeds(vocab)
    OUT.mkdir(parents=True, exist_ok=True)
    sd.to_csv(OUT / "probe_seeds.csv", index=False)
    print(f"seeds: {int(sd.label.sum())} verb forms, {int((sd.label == 0).sum())} non-verb forms", flush=True)

    occ = occurrences(texts, set(sd.form), rng)
    lab = dict(zip(sd.form, sd.label))
    grp = dict(zip(sd.form, sd.lemma))
    # balance: at most as many negative occurrences as positive ones
    pos_occ = [o for o in occ if lab[o["form"]] == 1]
    neg_occ = [o for o in occ if lab[o["form"]] == 0]
    neg_occ = rng.sample(neg_occ, min(len(neg_occ), len(pos_occ)))
    train = pos_occ + neg_occ
    print(f"training occurrences: {len(pos_occ)} verb, {len(neg_occ)} non-verb", flush=True)
    X = embed(train)
    y = np.array([lab[o["form"]] for o in train])
    g = np.array([grp[o["form"]] for o in train])
    st = np.array([o["stype"] for o in train])

    pred = np.zeros(len(y))
    for tr, te in GroupKFold(n_splits=5).split(X, y, g):
        clf = LogisticRegression(max_iter=2000, C=1.0).fit(X[tr], y[tr])
        pred[te] = clf.predict_proba(X[te])[:, 1]
    correct = (pred >= 0.5) == (y == 1)

    def ci(mask):
        k, n = int(correct[mask].sum()), int(mask.sum())
        lo, hi = wilson(k, n)
        return n, round(k / max(n, 1), 3), f"{lo:.2f}–{hi:.2f}"

    rows = [("all", *ci(np.ones(len(y), bool)))]
    rows += [(s, *ci(st == s)) for s in ("recipe", "medical", "other")]
    rows += [("verbs only", *ci(y == 1)), ("non-verbs only", *ci(y == 0))]
    rows += [(f"verbs, {s}", *ci((y == 1) & (st == s))) for s in ("recipe", "medical", "other")]
    ev = pd.DataFrame(rows, columns=["subset", "n", "accuracy", "95% CI"])
    # worst forms: where held-out predictions go wrong most
    per_form = pd.DataFrame({"form": [o["form"] for o in train], "label": y, "p": pred}) \
        .groupby(["form", "label"]).p.mean().reset_index()
    per_form["err"] = np.where(per_form.label == 1, 1 - per_form.p, per_form.p)
    worst = per_form.sort_values("err", ascending=False).head(25)

    clf = LogisticRegression(max_iter=2000, C=1.0).fit(X, y)
    cand = pd.read_csv(OUT / "candidates_raw.csv")
    cand = cand[(cand.n_generators >= 2) | (cand.silver_n >= 2) | (cand.gold_n >= 1)]
    cforms = set(cand.form) & vocab
    cocc = occurrences(texts, cforms, random.Random(SEED + 1))
    print(f"scoring {len(cforms)} candidate forms on {len(cocc)} occurrences…", flush=True)
    cp = clf.predict_proba(embed(cocc))[:, 1]
    sc = pd.DataFrame({"form": [o["form"] for o in cocc], "p": cp, "stype": [o["stype"] for o in cocc]})
    agg = sc.groupby("form").agg(n_occ=("p", "size"), verb_share=("p", lambda s: float((s >= 0.5).mean())),
                                 mean_p=("p", "mean")).reset_index()
    scored = cand.merge(agg, on="form", how="left")
    scored["verdict"] = np.select(
        [scored.n_occ.isna(), scored.verb_share >= 0.8, scored.verb_share >= 0.2],
        ["no occurrences in sample", "verb", "ambiguous"], "not verb")
    scored.sort_values(["verdict", "silver_n"], ascending=[True, False]).to_csv(OUT / "candidates_scored.csv", index=False)

    lines = ["# V0 verb probe (GysBERT, in-context token embeddings)", "",
             f"Texts: {len(texts)} works (39 T1b + cookbooks). Seeds: {int(sd.label.sum())} verb forms, "
             f"{int((sd.label == 0).sum())} non-verb forms (`probe_seeds.csv`). Training occurrences: "
             f"{len(pos_occ)} verb, {len(neg_occ)} non-verb.", "",
             "## Held-out evaluation (5-fold, grouped by lemma: the probe never saw the test verbs)", "",
             ev.to_markdown(index=False), "",
             "Gate (VERB_LEXICON.md V0): ≥ 0.9 overall and ≥ 0.85 per source type.", "",
             "## Forms the held-out probe gets most wrong", "", worst.round(2).to_markdown(index=False), "",
             "## Candidate verdicts (`candidates_scored.csv`)", "",
             "Verdict per form from its sampled occurrences: verb (≥ 80% verb readings), ambiguous (20–80%), "
             "not verb (< 20%).", "",
             scored.verdict.value_counts().to_frame("forms").to_markdown(), "",
             "Not in the current lexicon, verdict verb, by silver frequency (top 40):", "",
             scored[(scored.verdict == "verb") & ~scored.in_lexicon].sort_values("silver_n", ascending=False)
             .head(40)[["form", "frame", "silver_n", "gold_n", "n_occ", "verb_share"]].to_markdown(index=False), "",
             "In the current lexicon, verdict not verb:", "",
             scored[(scored.verdict == "not verb") & scored.in_lexicon]
             [["form", "frame", "generators", "n_occ", "verb_share"]].to_markdown(index=False), ""]
    (OUT / "probe_report.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
